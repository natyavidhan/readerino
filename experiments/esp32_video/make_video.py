"""Turns a video into a full-colour MJPEG blob that esp32_video.ino builds
into the ESP32's own flash (no SD card): baseline JPEG frames at the
largest size the 160x128 screen allows for the clip's aspect ratio, at the
highest JPEG quality that still fits the flash budget.

    python3 make_video.py <video> [--fps 30] [--budget-mb 2.4]

Writes (both gitignored -- they contain the video):
    video.bin       header + frame offset table + JPEG frames
    video_blob.S    assembler stub that .incbin's video.bin into flash

video.bin layout (little-endian):
    "MJV1", u16 width, u16 height, u16 fps, u16 reserved, u32 frameCount,
    u32 offsets[frameCount + 1] (from the start of the JPEG data), JPEGs
"""

import argparse
import struct
import subprocess
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCREEN_W, SCREEN_H = 160, 128


def fit_size(src: Path):
    out = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries",
                          "stream=width,height", "-of", "csv=p=0", str(src)],
                         capture_output=True, text=True, check=True).stdout
    iw, ih = (int(v) for v in out.strip().split(",")[:2])
    if iw * SCREEN_H >= ih * SCREEN_W:
        w, h = SCREEN_W, round(SCREEN_W * ih / iw)
    else:
        w, h = round(SCREEN_H * iw / ih), SCREEN_H
    return w - w % 2, h - h % 2


def encode(src: Path, fps: int, w: int, h: int, q: int):
    """JPEG frames at ffmpeg quality q (2 = best ... 31 = worst)."""
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(["ffmpeg", "-v", "error", "-i", str(src),
                        "-vf", f"fps={fps},scale={w}:{h}:flags=lanczos",
                        "-pix_fmt", "yuvj420p", "-q:v", str(q), f"{tmp}/f%05d.jpg"], check=True)
        return [p.read_bytes() for p in sorted(Path(tmp).glob("f*.jpg"))]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("video")
    ap.add_argument("--fps", type=int, default=30)
    ap.add_argument("--budget-mb", type=float, default=2.4,
                    help="max size of video.bin (4MB ESP32 with the Huge APP partition: ~3MB app space)")
    args = ap.parse_args()
    src = Path(args.video).resolve()
    w, h = fit_size(src)

    for q in range(2, 32):
        frames = encode(src, args.fps, w, h, q)
        size = sum(map(len, frames)) + 16 + 4 * (len(frames) + 1)
        print(f"quality {q:2d}: {len(frames)} frames, {size / 1e6:.2f} MB")
        if size <= args.budget_mb * 1e6:
            break
    else:
        raise SystemExit("doesn't fit even at the lowest quality -- lower --fps or raise --budget-mb")

    offsets, pos = [], 0
    for f in frames:
        offsets.append(pos)
        pos += len(f)
    offsets.append(pos)
    blob = HERE / "video.bin"
    with open(blob, "wb") as f:
        f.write(struct.pack("<4sHHHHI", b"MJV1", w, h, args.fps, 0, len(frames)))
        f.write(struct.pack(f"<{len(offsets)}I", *offsets))
        for fr in frames:
            f.write(fr)
    (HERE / "video_blob.S").write_text(
        "/* generated by make_video.py -- embeds video.bin in flash */\n"
        '    .section .rodata.video, "a"\n'
        "    .balign 4\n"
        "    .global video_start\n"
        "video_start:\n"
        f'    .incbin "{blob}"\n'
        "    .global video_end\n"
        "video_end:\n")
    print(f"wrote {blob.name}: {w}x{h} @ {args.fps}fps, {len(frames)} frames, JPEG quality {q}, "
          f"{blob.stat().st_size / 1e6:.2f} MB")


if __name__ == "__main__":
    main()
